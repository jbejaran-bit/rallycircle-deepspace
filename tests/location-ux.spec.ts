test('editing a location search cancels stale suggestions', async ({ page }) => {
  let releaseOld!: () => void
  const oldResponse = new Promise<void>(resolve => { releaseOld = resolve })
  await mockDiscovery(page)
  await page.route('**/api/geocode?**', async route => {
    const query = new URL(route.request().url()).searchParams.get('q')
    if (query === 'Old city') await oldResponse
    await route.fulfill({ json: { results: [query === 'Old city' ? { ...fixturePlace, displayName: 'Old city result' } : fixturePlace], cached: true } }).catch(() => undefined)
  })
  await page.goto(fixture('view=rallies'))
  await page.getByRole('button', { name: 'New session', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Create a session' })
  const search = dialog.getByLabel('Search courts or places', { exact: true })
  await search.fill('Old city')
  const oldRequest = page.waitForRequest(request => request.url().includes('/api/geocode?q=Old+city'))
  await dialog.getByRole('button', { name: 'Search places', exact: true }).click()
  await oldRequest
  await search.fill('Boston')
  await dialog.getByRole('button', { name: 'Search places', exact: true }).click()
  await expect(dialog.getByRole('button', { name: fixturePlace.displayName, exact: true })).toBeVisible()
  releaseOld()
  await expect(dialog.getByRole('button', { name: 'Old city result', exact: true })).toHaveCount(0)
  await expect(dialog.getByRole('button', { name: fixturePlace.displayName, exact: true })).toBeVisible()
})

