test('map/list numbers and lime selection stay synchronized with mouse and keyboard', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await mockDiscovery(page)
  await page.goto(fixture('view=courts'))
  await findCourts(page)
  const map = page.getByRole('region', { name: 'Nearby tennis courts map' })
  const first = map.getByRole('button', { name: 'Select Boston Common Tennis Courts', exact: true })
  const second = map.getByRole('button', { name: 'Select Charles River Tennis Courts', exact: true })
  await expect(first).toHaveAttribute('data-pin-number', '1')
  await expect(first).toHaveAttribute('aria-pressed', 'true')
  await expect(first).toHaveCSS('background-color', 'rgb(215, 252, 131)')
  await expect(second).not.toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await expect(second).not.toHaveCSS('background-color', 'rgb(215, 252, 131)')
  const secondRow = page.getByRole('list', { name: 'Nearby courts' }).getByRole('button', { name: /2\. Charles River Tennis Courts/ })
  await secondRow.click()
  await expect(second).toHaveAttribute('aria-pressed', 'true')
  await expect(second).toHaveCSS('background-color', 'rgb(215, 252, 131)')
  await first.focus()
  await first.press('Enter')
  await expect(first).toBeFocused()
  await expect(first).toHaveCSS('outline-style', 'solid')
  await expect(first).toHaveAttribute('aria-pressed', 'true')
  await second.focus()
  await second.press('Space')
  await expect(second).toBeFocused()
  await expect(secondRow).toHaveAttribute('aria-pressed', 'true')
  const size = await second.boundingBox()
  expect(size?.width).toBeGreaterThanOrEqual(44)
  expect(size?.height).toBeGreaterThanOrEqual(44)
})

