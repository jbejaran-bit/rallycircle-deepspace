const fixture = (query = '') => `/tests/ui-fixtures/index.html?${query}`

async function actions(page: Page) {
  const requests: Record<string, unknown>[] = []
  await page.route('**/api/actions/*', async route => {
    const input = route.request().postDataJSON()
    requests.push(input)
    const action = new URL(route.request().url()).pathname.split('/').at(-1)!
    const recordId = await page.evaluate(({ action, input }) => {
      const bridge = (globalThis as unknown as { __rallycircleFixtureAction: (action: string, input: Record<string, unknown>) => string }).__rallycircleFixtureAction
      return bridge(action, input)
    }, { action, input })
    await route.fulfill({ json: { success: true, data: { recordId } } })
  })
  return requests
}

